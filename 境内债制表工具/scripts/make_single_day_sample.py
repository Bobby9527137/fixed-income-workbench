def main() -> int:
    os.makedirs(RAW_DIR, exist_ok=True)
    config = load_config()
    jobs = (("单日样本_地方债.xlsx", LOCAL_ROWS, LOCAL_COLUMNS, "地方债-单日"),
            ("单日样本_信用债.xlsx", CREDIT_ROWS, CREDIT_COLUMNS, "信用债-单日"))
    for name, rows, columns, sheet in jobs:
        path = os.path.join(RAW_DIR, name)
        pd.DataFrame(rows, columns=columns).to_excel(path, index=False, sheet_name=sheet)
        print(f"已生成：{path}（{len(rows)} 行，{len(columns)} 列）")
        # 生成即自检：过引擎 → 行数 / 警告 / 播报预览
        for bond, sh, df in load_tasks(path, config):
            result, warnings = convert_dataframe(df, config, bond)
            hl = [m for m in (result.attrs.get("highlight_rows") or []) if m]
            print(f"  [自检] 识别={bond} 《{sh}》→ 输出 {len(result)} 行，"
                  f"警告 {len(warnings)} 条，标黄 {len(hl)} 行")
            for w in warnings:
                print(f"    ⚠ {w}")
            text = make_local_text(result) if bond == "地方债" else make_credit_text(result)
            print("  —— 播报文本（word=本周）——")
            print(text)
            print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
